/* ── Core functions ── */

/**
 * Detect the best language from the browser.
 * Maps navigator.language to one of: es, en, fr
 */
function detectLanguage() {
  const nav = (navigator.language || navigator.userLanguage || 'es').toLowerCase();
  if (nav.startsWith('fr')) return 'fr';
  if (nav.startsWith('en')) return 'en';
  return 'es'; // default
}

/**
 * Get current language from localStorage or detect.
 */
function getLang() {
  return localStorage.getItem('touri_lang') || detectLanguage();
}

/**
 * Set language and persist.
 */
function setLanguage(lang) {
  localStorage.setItem('touri_lang', lang);
  applyTranslations();
  // Dispatch event for dynamic components
  document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

/**
 * Translate a key, with optional replacements.
 * t('end.sub', { stops: 30, time: 40 })
 */
function t(key, replacements) {
  const lang = getLang();
  let text = TRANSLATIONS[lang]?.[key] || TRANSLATIONS['es']?.[key] || key;
  if (replacements) {
    Object.keys(replacements).forEach(k => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), replacements[k]);
    });
  }
  return text;
}

/**
 * Get time-aware greeting key.
 */
function getGreetingKey() {
  const hour = new Date().getHours();
  if (hour < 12) return 'explore.greeting.morning';
  if (hour < 20) return 'explore.greeting.afternoon';
  return 'explore.greeting.evening';
}

/**
 * Apply translations to all elements with data-i18n attribute.
 * Supports data-i18n-placeholder for inputs.
 */
function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (key === 'explore.greeting') {
      el.textContent = t(getGreetingKey());
    } else {
      el.textContent = t(key);
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.dataset.i18nHtml;
    el.innerHTML = t(key);
  });
}

/**
 * Initialize i18n on page load.
 */
function initI18n() {
  // Set lang if not set
  if (!localStorage.getItem('touri_lang')) {
    localStorage.setItem('touri_lang', detectLanguage());
  }
  applyTranslations();
}

// Auto-init on DOM ready
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}
